package authz

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/Measured-Health/mhai-multiagent/services/core/internal/httpx"
)

// FixturePrefix starts the test-only fixture routes (test build tag). The
// generators leave them out, so the published table is the same in every
// build.
const FixturePrefix = httpx.BasePath + "/_test/"

func published(table []RouteRule) []RouteRule {
	out := make([]RouteRule, 0, len(table))
	for _, rr := range table {
		if !strings.HasPrefix(rr.Pattern, FixturePrefix) {
			out = append(out, rr)
		}
	}
	return out
}

// jsonRule is one entry of permissions.json, for the Python services'
// checks.
type jsonRule struct {
	Method   string   `json:"method"`
	Pattern  string   `json:"pattern"`
	AnyRole  []string `json:"any_role"`
	Platform bool     `json:"platform"`
	StepUp   bool     `json:"step_up"`
	Write    bool     `json:"write"`
}

// JSON renders the table as permissions.json: a list of {method, pattern,
// any_role, platform, step_up, write}, sorted by pattern then method.
func JSON(table []RouteRule) ([]byte, error) {
	rows := []jsonRule{}
	for _, rr := range published(table) {
		roles := rr.Rule.AnyRole
		if roles == nil {
			roles = []string{}
		}
		rows = append(rows, jsonRule{Method: rr.Method, Pattern: rr.Pattern, AnyRole: roles,
			Platform: rr.Rule.Platform, StepUp: rr.Rule.StepUp, Write: rr.Rule.Write})
	}
	b, err := json.MarshalIndent(rows, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// Markdown renders the table for docs/specs/generated/permissions.md.
func Markdown(table []RouteRule) []byte {
	var b bytes.Buffer
	b.WriteString("# Permission table\n\n")
	b.WriteString("Generated by `services/core/cmd/permgen` from the core service's routes. Do not edit by hand;\n")
	b.WriteString("run `go run ./cmd/permgen` in `services/core` after changing a route.\n\n")
	b.WriteString("- **Access:** `public` needs no token; `signed in` is any account whose session meets its two-step policy;\n")
	b.WriteString("  `enrolment` also accepts a session limited to setting up two-step.\n")
	b.WriteString("- **Roles:** any one of them. Roles combine on clinical accounts.\n")
	b.WriteString("- **Audience:** `platform` needs `X-MHAI-Audience: platform` and a platform account (else 403 `not_platform`);\n")
	b.WriteString("  `clinical` refuses platform accounts (403 `forbidden`); `both` (the account's own routes) is either account on its own audience.\n")
	b.WriteString("- **Write:** auditors get 403 `forbidden`; they are also refused every method but GET, HEAD and OPTIONS outside the `both` routes.\n")
	b.WriteString("- Another hospital's resource is 404 `not_found`, never 403.\n\n")
	b.WriteString("| Method | Path | Access | Roles | Audience | Two-step session | Step-up | Write |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, rr := range published(table) {
		r := rr.Rule
		access := "signed in"
		switch {
		case r.Public:
			access = "public"
		case r.MFAEnrol:
			access = "enrolment"
		}
		roles := "any"
		if len(r.AnyRole) > 0 {
			roles = "`" + strings.Join(r.AnyRole, "`, `") + "`"
		}
		aud := "clinical"
		switch {
		case r.Public:
			aud = "-"
		case r.Platform:
			aud = "platform"
		case r.SelfService:
			aud = "both"
		}
		if r.Public {
			roles = "-"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %s |\n",
			rr.Method, rr.Pattern, access, roles, aud, yes(r.NeedsMFA), yes(r.StepUp), yes(r.Write))
	}
	return b.Bytes()
}

func yes(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
